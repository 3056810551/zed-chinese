def enrich():
    if not ZH_CN_FILE.exists():
        print(f"Error: {ZH_CN_FILE} does not exist.")
        return

    with open(ZH_CN_FILE, "r", encoding="utf-8") as f:
        current_dict = json.load(f)

    updated = 0
    for k, v in TRANSLATIONS_MAP.items():
        if k in current_dict:
            if not current_dict[k] or current_dict[k] != v:
                current_dict[k] = v
                updated += 1
        else:
            current_dict[k] = v
            updated += 1

    with open(ZH_CN_FILE, "w", encoding="utf-8") as f:
        json.dump(current_dict, f, indent=2, ensure_ascii=False)

    translated = sum(1 for v in current_dict.values() if v.strip())
    total = len(current_dict)
    print(f"Enrichment Complete!")
    print(f"  - Newly translated / updated: {updated}")
    print(f"  - Total translated entries: {translated} / {total} ({translated / total * 100:.1f}%)")

if __name__ == "__main__":
    enrich()
